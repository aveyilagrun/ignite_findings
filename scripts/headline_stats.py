"""
Reproduce the headline numbers of the multi-country study (Study 2) in one place.

Loads processed_data/*_<country>_genders.csv and cleans it in three steps:
  1. The same cleaning as analysis/analysis.ipynb (cells 1-3), giving 19,538 rows:
       * Country is taken from the file name.
       * Publication Year kept only if 2010 <= year <= 2025.
       * Publication Title kept only if it is one of the six valid journal titles.
  2. Duplicate rows are removed: one row per (Item DOI, Country). The
     solar_energy_<country> files also contain the Solar Energy Materials and
     Solar Cells articles, so those were counted twice; a few files also repeat rows.
  3. Rows with no first-author name are removed. The gender API was called with
     an empty name for these, so their "male" label is not a prediction.
The notebook does steps 2 and 3 nowhere, so its numbers differ slightly.
No confidence filtering is applied unless stated.

Unit of analysis = one record = one article x country. An article whose
authors are affiliated with two study countries appears once under each, so
record counts are larger than unique-DOI counts (reported below).

Usage (from the repository root):
    python scripts/headline_stats.py                # writes results/headline_stats.md and .json
    python scripts/headline_stats.py --data processed_data --out results
"""
import argparse
import glob
import json
import os

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf
from scipy import stats

VALID_JOURNALS = [
    "Applied Catalysis A: General",
    "Energy Policy",
    "International Journal of Greenhouse Gas Control",
    "International Journal of Hydrogen Energy",
    "Solar Energy",
    "Solar Energy Materials and Solar Cells",
]
COUNTRIES = {"uk": "UK", "us": "USA", "canada": "Canada", "france": "France",
             "germany": "Germany", "singapore": "Singapore",
             "south_africa": "South Africa", "switzerland": "Switzerland"}
METRICS = ["Citations", "Usages", "Captures", "Mentions", "Social Media"]


def load(data_dir):
    frames = []
    for path in sorted(glob.glob(os.path.join(data_dir, "*_genders.csv"))):
        base = os.path.basename(path)[: -len("_genders.csv")]
        key = next(k for k in sorted(COUNTRIES, key=len, reverse=True) if base.endswith("_" + k))
        d = pd.read_csv(path)
        d["Country"] = COUNTRIES[key]
        d["source_file"] = os.path.basename(path)
        frames.append(d)
    raw = pd.concat(frames, ignore_index=True)
    df = raw[(raw["Publication Year"] >= 2010) & (raw["Publication Year"] <= 2025)]
    df = df[df["Publication Title"].isin(VALID_JOURNALS)].copy()
    steps = {"rows_notebook_cleaning": len(df)}
    df = df.drop_duplicates(["Item DOI", "Country"])
    steps["rows_after_dedup"] = len(df)
    df = df[df["First Author"].notna()].copy()
    steps["rows_final"] = len(df)
    df["female"] = (df["Gender (First Author)"] == "female").astype(int)
    df["year"] = df["Publication Year"].astype(int)
    # first name is only initials (e.g. "O. V. Chub"): gender cannot really be inferred
    df["initials_only"] = df["First Author"].str.split().str[0].str.match(r"^(.\.?|(.\.)+)$")
    df.attrs["steps"] = steps
    return raw, df


def wilson(k, n, z=1.96):
    p = k / n
    den = 1 + z ** 2 / n
    c = (p + z ** 2 / (2 * n)) / den
    h = z * np.sqrt(p * (1 - p) / n + z ** 2 / (4 * n ** 2)) / den
    return 100 * (c - h), 100 * (c + h)


def share_table(df, by):
    g = df.groupby(by)["female"].agg(["sum", "count"])
    out = []
    for k, r in g.iterrows():
        lo, hi = wilson(r["sum"], r["count"])
        out.append({by: k, "n": int(r["count"]), "female_n": int(r["sum"]),
                    "female_pct": 100 * r["sum"] / r["count"], "ci_low": lo, "ci_high": hi})
    return pd.DataFrame(out).sort_values("female_pct", ascending=False)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="processed_data")
    ap.add_argument("--out", default="results")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)

    raw, df = load(a.data)
    R = {}  # machine-readable results
    md = ["# Headline statistics (auto-generated by scripts/headline_stats.py)", "",
          "Do not edit by hand. Re-run the script after any data change.", ""]

    # ---------------- sample ----------------
    st = df.attrs["steps"]
    R["rows_raw"] = len(raw)
    R["rows_notebook_cleaning"] = st["rows_notebook_cleaning"]
    R["rows_after_dedup"] = st["rows_after_dedup"]
    R["rows_clean"] = len(df)
    R["unique_doi_clean"] = int(df["Item DOI"].nunique())
    R["dropped_bad_year"] = int(((raw["Publication Year"] < 2010) | (raw["Publication Year"] > 2025)).sum())
    R["initials_only"] = int(df["initials_only"].sum())
    dup = df.groupby("Item DOI")["Country"].nunique()
    R["doi_in_multiple_countries"] = int((dup > 1).sum())
    md += ["## 1. Sample", "",
           f"- Raw rows (48 files): {R['rows_raw']:,}",
           f"- After the notebook's cleaning (2010-2025, six valid journal titles): {st['rows_notebook_cleaning']:,}",
           f"- After removing duplicate rows (same DOI and country): {st['rows_after_dedup']:,} "
           f"({st['rows_notebook_cleaning'] - st['rows_after_dedup']:,} removed)",
           f"- After removing rows with no first-author name: **{R['rows_clean']:,}** article-country records "
           f"({st['rows_after_dedup'] - R['rows_clean']:,} removed). This is the analysis sample.",
           f"- Unique articles (DOIs): {R['unique_doi_clean']:,} "
           f"({R['doi_in_multiple_countries']:,} appear under more than one country)",
           f"- Records whose first-author first name is only initials: {R['initials_only']:,} "
           "(kept in the main analysis; see section 7)", ""]
    yc = df["year"].value_counts().sort_index()
    md += ["Records per year: " + ", ".join(f"{y}: {n}" for y, n in yc.items()), ""]

    # ---------------- representation ----------------
    k, n = df["female"].sum(), len(df)
    lo, hi = wilson(k, n)
    R["female_first_pct"] = 100 * k / n
    R["female_first_ci"] = [lo, hi]
    md += ["## 2. Female first authorship", "",
           f"- Overall: **{100*k/n:.1f}%** ({k:,}/{n:,}; 95% CI {lo:.1f}-{hi:.1f})", ""]
    for by, label in [("Country", "country"), ("Publication Title", "journal")]:
        t = share_table(df, by)
        chi2, p, dof, _ = stats.chi2_contingency(pd.crosstab(df[by], df["female"]))
        R[f"by_{label}"] = t.to_dict("records")
        R[f"chi2_{label}"] = {"chi2": chi2, "dof": dof, "p": p}
        md += [f"### By {label} (chi-square = {chi2:.2f}, df = {dof}, p = {p:.2g})", "",
               f"| {label} | n | female % | 95% CI |", "|---|---|---|---|"]
        md += [f"| {r[by]} | {r['n']:,} | {r['female_pct']:.1f} | {r['ci_low']:.1f}-{r['ci_high']:.1f} |"
               for _, r in t.iterrows()]
        md.append("")

    # ---------------- temporal trend ----------------
    yearly = df.groupby("year")["female"].mean() * 100
    R["yearly_female_pct"] = {int(y): v for y, v in yearly.items()}
    lr_all = stats.linregress(yearly.index, yearly.values)
    y24 = yearly[yearly.index <= 2024]
    lr_24 = stats.linregress(y24.index, y24.values)
    d24 = df[df["year"] <= 2024]
    logit = smf.logit("female ~ I(year - 2010)", data=d24).fit(disp=0)
    b, pl = logit.params.iloc[1], logit.pvalues.iloc[1]
    R["trend"] = {"yearly_r_2010_2025": lr_all.rvalue, "yearly_p_2010_2025": lr_all.pvalue,
                  "yearly_r_2010_2024": lr_24.rvalue, "yearly_p_2010_2024": lr_24.pvalue,
                  "yearly_slope_pp_2010_2024": lr_24.slope,
                  "logit_or_per_year_2010_2024": float(np.exp(b)), "logit_p_2010_2024": pl}
    md += ["## 3. Trend over time", "",
           "| year | " + " | ".join(str(y) for y in yearly.index) + " |",
           "|---|" + "---|" * len(yearly),
           "| female % | " + " | ".join(f"{v:.1f}" for v in yearly.values) + " |", "",
           f"- Year-level regression, 2010-2025 (as in analysis.ipynb): r = {lr_all.rvalue:.3f}, p = {lr_all.pvalue:.3f}. "
           f"2025 is a partial year (n = {int(yc.get(2025, 0))}, {yearly.get(2025, float('nan')):.1f}% female) and dominates this result.",
           f"- Year-level regression, 2010-2024: r = {lr_24.rvalue:.2f}, p = {lr_24.pvalue:.4f}, slope = {lr_24.slope:+.2f} percentage points/year.",
           f"- Article-level logistic regression, 2010-2024: odds ratio per year = {np.exp(b):.3f}, p = {pl:.2g}.", ""]

    # ---------------- impact ----------------
    m = df.dropna(subset=["Citations"])
    cm, cf = m.loc[m.female == 0, "Citations"], m.loc[m.female == 1, "Citations"]
    u = stats.mannwhitneyu(cm, cf, alternative="two-sided")
    R["citations"] = {"mean_male": cm.mean(), "mean_female": cf.mean(), "median_male": cm.median(),
                      "median_female": cf.median(), "pct_more_male": 100 * (cm.mean() / cf.mean() - 1),
                      "mannwhitney_p": u.pvalue, "n_male": len(cm), "n_female": len(cf)}
    md += ["## 4. Impact metrics by first-author gender", "",
           f"Records with metrics: {len(m):,} (metrics missing for {len(df)-len(m)} records). "
           "`Citations` is the citation count in the Elsevier/PlumX metrics columns (the column the notebook used for its citation gap).", "",
           "| metric | mean male | mean female | median male | median female | Mann-Whitney p |",
           "|---|---|---|---|---|---|"]
    R["other_metrics"] = {}
    for col in METRICS + ["Citations (Crossref)", "First Author H-Index"]:
        x = df.dropna(subset=[col])
        a_, b_ = x.loc[x.female == 0, col], x.loc[x.female == 1, col]
        p = stats.mannwhitneyu(a_, b_, alternative="two-sided").pvalue
        R["other_metrics"][col] = {"mean_male": a_.mean(), "mean_female": b_.mean(),
                                   "median_male": a_.median(), "median_female": b_.median(), "p": p}
        md.append(f"| {col} | {a_.mean():.2f} | {b_.mean():.2f} | {a_.median():.1f} | {b_.median():.1f} | {p:.2g} |")
    c = R["citations"]
    md += ["", f"- Raw gap: male first-authored papers receive **{c['pct_more_male']:.2f}%** more citations on average "
               f"({c['mean_male']:.2f} vs {c['mean_female']:.2f}); medians {c['median_male']:.0f} vs {c['median_female']:.0f}; "
               f"Mann-Whitney p = {c['mannwhitney_p']:.2g}.", ""]

    # controlled models: log(1 + citations)
    mm = m.dropna(subset=["First Author H-Index"]).copy()
    mm["log_cit"] = np.log1p(mm["Citations"])
    mm["log_h"] = np.log1p(mm["First Author H-Index"])
    mm["journal"] = mm["Publication Title"]
    specs = {
        "M1 gender only": "log_cit ~ female",
        "M2 + year, journal, country": "log_cit ~ female + C(year) + C(journal) + C(Country)",
        "M3 + first-author h-index": "log_cit ~ female + C(year) + C(journal) + C(Country) + log_h",
    }
    md += ["Controlled models (OLS on log(1 + citations), HC1 robust SE; coefficient converted to % difference female vs male):", "",
           "| model | % difference (female vs male) | 95% CI | p | n |", "|---|---|---|---|---|"]
    R["citation_models"] = {}
    for name, f in specs.items():
        fit = smf.ols(f, data=mm).fit(cov_type="HC1")
        bb, se, p = fit.params["female"], fit.bse["female"], fit.pvalues["female"]
        pct, l, h = [100 * (np.exp(v) - 1) for v in (bb, bb - 1.96 * se, bb + 1.96 * se)]
        R["citation_models"][name] = {"pct": pct, "ci": [l, h], "p": p, "n": int(fit.nobs)}
        md.append(f"| {name} | {pct:+.1f}% | {l:+.1f} to {h:+.1f} | {p:.2g} | {int(fit.nobs):,} |")
    md.append("")

    # gap by period (draft claimed narrowing after 2020)
    md += ["Raw citation gap by period:", "", "| period | mean male | mean female | % more for male | Mann-Whitney p |", "|---|---|---|---|---|"]
    R["gap_by_period"] = {}
    for lab, cond in [("2010-2019", m.year <= 2019), ("2020-2025", m.year >= 2020)]:
        s = m[cond]
        a_, b_ = s.loc[s.female == 0, "Citations"], s.loc[s.female == 1, "Citations"]
        p = stats.mannwhitneyu(a_, b_, alternative="two-sided").pvalue
        R["gap_by_period"][lab] = {"male": a_.mean(), "female": b_.mean(), "pct": 100 * (a_.mean() / b_.mean() - 1), "p": p}
        md.append(f"| {lab} | {a_.mean():.2f} | {b_.mean():.2f} | {100*(a_.mean()/b_.mean()-1):+.1f}% | {p:.2g} |")
    md.append("")

    # ---------------- regional patterns ----------------
    md += ["## 5. Regional patterns", "", "### Share of each impact metric by country (% of metric total)", "",
           "| country | papers % | " + " | ".join(METRICS) + " |", "|---|---|" + "---|" * len(METRICS)]
    tot = df[METRICS].sum()
    R["metric_share"] = {}
    for cty, g in df.groupby("Country"):
        sh = 100 * g[METRICS].sum() / tot
        R["metric_share"][cty] = {"papers": 100 * len(g) / len(df), **sh.to_dict()}
        md.append(f"| {cty} | {100*len(g)/len(df):.1f} | " + " | ".join(f"{v:.1f}" for v in sh.values) + " |")
    # coverage check: are usage / social media recorded evenly across countries?
    md += ["", "### Coverage of usage and social media metrics (% of each country's records with a non-zero value)", "",
           "| country | Usages > 0 | Social Media > 0 |", "|---|---|---|"]
    R["metric_coverage"] = {}
    for cty, g in df.groupby("Country"):
        cu, cs = 100 * (g["Usages"] > 0).mean(), 100 * (g["Social Media"] > 0).mean()
        R["metric_coverage"][cty] = {"usages_nonzero_pct": cu, "social_nonzero_pct": cs}
        md.append(f"| {cty} | {cu:.1f} | {cs:.1f} |")
    top_u = 100 * df["Usages"].max() / df["Usages"].sum()
    top5_s = 100 * df["Social Media"].nlargest(5).sum() / df["Social Media"].sum()
    R["metric_concentration"] = {"largest_usage_record_pct": top_u, "top5_social_records_pct": top5_s}
    md += ["", f"- The single largest record holds {top_u:.1f}% of all usage; the five largest records hold "
               f"{top5_s:.1f}% of all social media counts. Country shares of these two metrics are therefore not meaningful.", ""]
    md += ["### Journal mix within each country (% of that country's records)", ""]
    jm = pd.crosstab(df["Country"], df["Publication Title"], normalize="index") * 100
    R["journal_mix"] = jm.round(2).to_dict("index")
    short = {j: j.replace("International Journal of", "IJ").replace("Solar Energy Materials and Solar Cells", "SEMSC")
             .replace("Applied Catalysis A: General", "Appl. Catal. A") for j in jm.columns}
    md += ["| country | " + " | ".join(short[j] for j in jm.columns) + " |", "|---|" + "---|" * len(jm.columns)]
    md += [f"| {c_} | " + " | ".join(f"{v:.1f}" for v in r.values) + " |" for c_, r in jm.iterrows()]
    md.append("")

    # ---------------- gender-classification confidence ----------------
    conf = "Gender likelihood (First Author)"
    md += ["## 6. Namsor confidence (first authors)", "",
           f"- Mean confidence: overall {df[conf].mean():.3f}; male-predicted {df.loc[df.female==0, conf].mean():.3f}; "
           f"female-predicted {df.loc[df.female==1, conf].mean():.3f}", "",
           "| minimum confidence | rows kept | female % |", "|---|---|---|"]
    R["threshold"] = {}
    for t in [0.0, 0.6, 0.7, 0.8, 0.9]:
        s = df[df[conf] >= t]
        R["threshold"][t] = {"n": len(s), "female_pct": 100 * s["female"].mean()}
        md.append(f"| {'none' if t == 0 else t} | {len(s):,} | {100*s['female'].mean():.1f} |")
    md.append("")
    md += ["Female share by confidence band (shows where the female-predicted names sit):", "",
           "| confidence band | records | female % |", "|---|---|---|"]
    R["confidence_bands"] = {}
    edges = [0.5, 0.6, 0.7, 0.8, 0.9, 1.0001]
    for lo_, hi_ in zip(edges[:-1], edges[1:]):
        s = df[(df[conf] >= lo_) & (df[conf] < hi_)]
        lab = f"{lo_:.1f}-{min(hi_, 1.0):.1f}"
        R["confidence_bands"][lab] = {"n": len(s), "female_pct": 100 * s["female"].mean()}
        md.append(f"| {lab} | {len(s):,} | {100*s['female'].mean():.1f} |")
    md.append("")

    # spot check: how confident is the classifier for unambiguous given names?
    given = df["First Author"].str.split().str[0].str.lower()
    md += ["Spot check on unambiguous given names (why thresholds remove women: even clear female names get moderate confidence):", "",
           "| given name | records | predicted female % | mean confidence |", "|---|---|---|---|"]
    R["name_spot_check"] = {}
    for nm in ["sarah", "laura", "julia", "anna", "maria", "michael", "thomas", "david"]:
        s = df[given == nm]
        R["name_spot_check"][nm] = {"n": len(s), "female_pct": 100 * s["female"].mean(), "mean_conf": s[conf].mean()}
        md.append(f"| {nm.capitalize()} | {len(s)} | {100*s['female'].mean():.0f} | {s[conf].mean():.2f} |")
    md.append("")

    # ---------------- robustness ----------------
    md += ["## 7. Robustness checks", "",
           "### Female share by country and journal at minimum-confidence thresholds", "",
           "`kept` is the share of that group's records with confidence >= 0.7.", "",
           "| group | none | >= 0.6 | >= 0.7 | kept at 0.7 (%) | mean confidence |", "|---|---|---|---|---|---|"]
    R["robust_groups"] = {}
    for by in ["Country", "Publication Title"]:
        order = df.groupby(by)["female"].mean().sort_values(ascending=False).index
        for k_ in order:
            g = df[df[by] == k_]
            v = [100 * g.loc[g[conf] >= t, "female"].mean() for t in (0, 0.6, 0.7)]
            kept = 100 * (g[conf] >= 0.7).mean()
            R["robust_groups"][k_] = {"none": v[0], "0.6": v[1], "0.7": v[2], "kept_0.7_pct": kept, "mean_conf": g[conf].mean()}
            md.append(f"| {k_} | {v[0]:.1f} | {v[1]:.1f} | {v[2]:.1f} | {kept:.0f} | {g[conf].mean():.2f} |")
    md.append("")

    dj = df.assign(journal=df["Publication Title"])
    jl = smf.logit("female ~ C(Country, Treatment('Germany')) + C(journal, Treatment('Solar Energy'))", data=dj).fit(disp=0)
    md += ["### Country and journal together (logistic regression; odds ratios vs Germany and vs Solar Energy)", "",
           "| term | odds ratio | p |", "|---|---|---|"]
    R["joint_model"] = {}
    for term in jl.params.index[1:]:
        name = term.split("[T.")[1].rstrip("]")
        R["joint_model"][name] = {"or": float(np.exp(jl.params[term])), "p": float(jl.pvalues[term])}
        md.append(f"| {name} | {np.exp(jl.params[term]):.2f} | {jl.pvalues[term]:.2g} |")
    md.append("")

    md += ["### Trend 2010-2024 under alternative choices", "",
           "| variant | slope (pp/year) | year-level p | logistic OR per year | p |", "|---|---|---|---|---|"]
    R["robust_trend"] = {}
    variants = {"main analysis": d24,
                "confidence >= 0.6": d24[d24[conf] >= 0.6],
                "confidence >= 0.7": d24[d24[conf] >= 0.7],
                "excluding initials-only names": d24[~d24["initials_only"]],
                "one row per article (unique DOI)": d24.drop_duplicates("Item DOI")}
    for lab, s in variants.items():
        yv = s.groupby("year")["female"].mean() * 100
        lr = stats.linregress(yv.index, yv.values)
        lg = smf.logit("female ~ I(year - 2010)", data=s).fit(disp=0)
        R["robust_trend"][lab] = {"slope": lr.slope, "p": lr.pvalue, "or": float(np.exp(lg.params.iloc[1])), "or_p": float(lg.pvalues.iloc[1])}
        md.append(f"| {lab} | {lr.slope:+.2f} | {lr.pvalue:.3f} | {np.exp(lg.params.iloc[1]):.3f} | {lg.pvalues.iloc[1]:.2g} |")
    lgc = smf.logit("female ~ I(year - 2010) + C(Country) + C(journal)", data=d24.assign(journal=d24["Publication Title"])).fit(disp=0)
    R["robust_trend"]["with country and journal controls"] = {"or": float(np.exp(lgc.params["I(year - 2010)"])),
                                                              "or_p": float(lgc.pvalues["I(year - 2010)"])}
    md += [f"| with country and journal controls | - | - | {np.exp(lgc.params['I(year - 2010)']):.3f} | {lgc.pvalues['I(year - 2010)']:.2g} |", "",
           f"- Mean confidence by year falls from {d24[d24.year == 2010][conf].mean():.3f} (2010) to "
           f"{d24[d24.year == 2024][conf].mean():.3f} (2024), i.e. names became slightly harder to classify.",
           f"- Female share excluding initials-only names (all years): {100 * df.loc[~df['initials_only'], 'female'].mean():.1f}% "
           f"(n = {int((~df['initials_only']).sum()):,}).",
           f"- Female share with one row per article (all years): {100 * df.drop_duplicates('Item DOI')['female'].mean():.1f}% "
           f"(n = {df['Item DOI'].nunique():,}).", ""]

    md += ["### Citation models under alternative choices (% difference, female vs male first author)", "",
           "| variant | M2: + year, journal, country | p | M3: + h-index | p | n |", "|---|---|---|---|---|---|"]
    R["robust_citations"] = {}
    f2, f3 = specs["M2 + year, journal, country"], specs["M3 + first-author h-index"]

    def pct_p(fit):
        return 100 * (np.exp(fit.params["female"]) - 1), fit.pvalues["female"]

    cvars = {"main analysis (OLS on log citations)": mm,
             "confidence >= 0.6": mm[mm[conf] >= 0.6],
             "confidence >= 0.7": mm[mm[conf] >= 0.7],
             "excluding initials-only names": mm[~mm["initials_only"]],
             "one row per article (unique DOI)": mm.drop_duplicates("Item DOI")}
    for lab, s in cvars.items():
        (p2, q2), (p3, q3) = pct_p(smf.ols(f2, data=s).fit(cov_type="HC1")), pct_p(smf.ols(f3, data=s).fit(cov_type="HC1"))
        R["robust_citations"][lab] = {"m2_pct": p2, "m2_p": q2, "m3_pct": p3, "m3_p": q3, "n": len(s)}
        md.append(f"| {lab} | {p2:+.1f}% | {q2:.2g} | {p3:+.1f}% | {q3:.2g} | {len(s):,} |")
    import statsmodels.api as sm
    pf2 = pct_p(smf.glm(f2.replace("log_cit", "Citations"), data=mm, family=sm.families.Poisson()).fit(cov_type="HC1"))
    pf3 = pct_p(smf.glm(f3.replace("log_cit", "Citations"), data=mm, family=sm.families.Poisson()).fit(cov_type="HC1"))
    R["robust_citations"]["Poisson (ratio of mean citations)"] = {"m2_pct": pf2[0], "m2_p": pf2[1], "m3_pct": pf3[0], "m3_p": pf3[1], "n": len(mm)}
    md += [f"| Poisson regression (ratio of mean citations) | {pf2[0]:+.1f}% | {pf2[1]:.2g} | {pf3[0]:+.1f}% | {pf3[1]:.2g} | {len(mm):,} |", ""]
    ua = mm.drop_duplicates("First Author")
    hf, hm = ua.loc[ua.female == 1, "First Author H-Index"], ua.loc[ua.female == 0, "First Author H-Index"]
    R["h_index_unique_authors"] = {"n": len(ua), "mean_female": hf.mean(), "mean_male": hm.mean(),
                                   "median_female": hf.median(), "median_male": hm.median(),
                                   "p": stats.mannwhitneyu(hf, hm, alternative="two-sided").pvalue}
    md += [f"- h-index counted once per first author ({len(ua):,} unique names): female mean {hf.mean():.1f}, median {hf.median():.0f}; "
           f"male mean {hm.mean():.1f}, median {hm.median():.0f}; Mann-Whitney p = {R['h_index_unique_authors']['p']:.2g}.", ""]

    with open(os.path.join(a.out, "headline_stats.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(a.out, "headline_stats.json"), "w", encoding="utf-8") as fh:
        json.dump(R, fh, indent=1, default=float)
    print("\n".join(md))



"""
Additional analyses beyond the headline numbers (seniority, repeat authorship, teams,
citation tails, trends by journal and country, keywords).

Uses the same cleaned data as scripts/headline_stats.py.
Usage (from the repository root):
    python scripts/extra_analysis.py        # writes results/extra_analysis.md
"""
import ast
import os
import sys
import warnings

import numpy as np
import pandas as pd
import statsmodels.formula.api as smf
from scipy import stats

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from headline_stats import load, wilson  # noqa: E402

warnings.filterwarnings("ignore")
CONF = "Gender likelihood (First Author)"
md = []


def out(*lines):
    md.extend(lines)


def pct(s):
    return 100 * s.mean()


def table(header, rows):
    out("| " + " | ".join(header) + " |", "|" + "---|" * len(header))
    for r in rows:
        out("| " + " | ".join(str(x) for x in r) + " |")
    out("")


def parse_list(x):
    try:
        v = ast.literal_eval(x)
        return v if isinstance(v, list) else []
    except Exception:
        return []


def parse_h(x):
    if not isinstance(x, str):
        return []
    vals = []
    for p in x.split(","):
        try:
            vals.append(float(p))
        except ValueError:
            pass
    return vals


def trend(d):
    y = d.groupby("year")["female"].mean() * 100
    lr = stats.linregress(y.index, y.values)
    lg = smf.logit("female ~ I(year - 2010)", data=d).fit(disp=0)
    return lr.slope, lr.pvalue, float(np.exp(lg.params.iloc[1])), float(lg.pvalues.iloc[1])


def main():
    _, df = load("processed_data")
    df["journal"] = df["Publication Title"]
    df["coauthors"] = df["Authors"].apply(parse_list)
    df["n_authors"] = 1 + df["coauthors"].str.len()
    df["co_h"] = df["Authors H-index"].apply(parse_h)
    df["co_h_max"] = df["co_h"].apply(lambda v: max(v) if v else np.nan)
    df["h"] = df["First Author H-Index"]
    art = df.drop_duplicates("Item DOI").copy()  # one row per article
    overall = pct(df["female"])

    out("# Additional analyses (auto-generated by scripts/extra_analysis.py)", "",
        f"Sample: {len(df):,} article-country records, {len(art):,} unique articles. "
        f"Overall female first-author share: {overall:.1f}%.",
        "Gender is the Namsor prediction for the first author, no confidence threshold unless stated.", "")

    # ---------- 1. seniority gradient ----------
    out("## 1. Female share by first-author seniority (h-index)", "")
    bins = [-1, 2, 5, 10, 20, 40, 1000]
    labels = ["0-2", "3-5", "6-10", "11-20", "21-40", "41+"]
    auth = art.sort_values("year").drop_duplicates("First Author").copy()  # one row per first author
    rows = []
    for name, d in [("articles", art), ("unique first authors", auth), ("articles, confidence >= 0.6", art[art[CONF] >= 0.6])]:
        b = pd.cut(d["h"], bins=bins, labels=labels)
        g = d.groupby(b)["female"].agg(["mean", "count"])
        rows.append([name] + [f"{100*m:.1f} (n={int(n):,})" for m, n in zip(g["mean"], g["count"])])
    table(["unit"] + ["h " + l for l in labels], rows)
    lg = smf.logit("female ~ np.log1p(h) + C(year) + C(journal)", data=art).fit(disp=0)
    out(f"- Logistic regression (articles, with year and journal controls): odds ratio per unit of log(1 + h-index) = "
        f"{np.exp(lg.params['np.log1p(h)']):.2f}, p = {lg.pvalues['np.log1p(h)']:.2g}.", "")

    # ---------- 2. repeat first authorship ----------
    out("## 2. Repeat first authorship", "")
    per = art.groupby("First Author").agg(n=("Item DOI", "nunique"), female=("female", "first"),
                                          first_year=("year", "min"), last_year=("year", "max"))
    rows = []
    for gname, gv in [("female", 1), ("male", 0)]:
        p = per[per.female == gv]
        rows.append([gname, f"{len(p):,}", f"{p.n.mean():.2f}", f"{100*(p.n >= 2).mean():.1f}", f"{100*(p.n >= 3).mean():.1f}",
                     f"{100*(p.n >= 5).mean():.1f}", f"{(p.last_year - p.first_year)[p.n >= 2].mean():.1f}"])
    table(["first-author gender", "unique authors", "mean first-author articles", "% with 2+", "% with 3+", "% with 5+",
           "mean years between first and last (2+ only)"], rows)
    ct = pd.crosstab(per.female, per.n >= 2)
    out(f"- Chi-square test for 2+ articles by gender: p = {stats.chi2_contingency(ct)[1]:.2g}.",
        f"- Female share among unique first authors: {pct(per.female):.1f}%; among those with one article {pct(per[per.n == 1].female):.1f}%, "
        f"2-4 articles {pct(per[(per.n >= 2) & (per.n <= 4)].female):.1f}%, 5+ articles {pct(per[per.n >= 5].female):.1f}%.",
        "- Authors are matched by exact name, so name variants split one person and common names merge several.", "")

    # new entrants per year
    out("### Female share among new first authors (first appearance in the dataset), by year", "")
    ent = per[(per.first_year >= 2012) & (per.first_year <= 2024)].groupby("first_year")["female"].agg(["mean", "count"])
    table(["year"] + [str(y) for y in ent.index], [["female %"] + [f"{100*v:.1f}" for v in ent["mean"]],
                                                  ["new authors"] + [int(v) for v in ent["count"]]])
    lr = stats.linregress(ent.index, 100 * ent["mean"])
    out(f"- Trend among new first authors 2012-2024: {lr.slope:+.2f} pp/year, p = {lr.pvalue:.3f}. "
        "(2010-2011 are left out because everyone looks new at the start of the data.)", "")

    # ---------- 3. teams ----------
    out("## 3. Team size and collaborators", "")
    rows = []
    for gname, gv in [("female", 1), ("male", 0)]:
        d = art[art.female == gv]
        senior = (d["h"] >= d["co_h_max"])[d["co_h_max"].notna()]
        rows.append([gname, f"{d.n_authors.mean():.2f}", f"{d.n_authors.median():.0f}", f"{100*(d.n_authors == 1).mean():.1f}",
                     f"{d.co_h_max.mean():.1f}", f"{d.co_h_max.median():.0f}", f"{100*senior.mean():.1f}"])
    table(["first-author gender", "mean authors", "median authors", "% solo-authored", "mean of highest co-author h-index",
           "median of highest co-author h-index", "% where first author has the highest h-index in the team"], rows)
    f_, m_ = art[art.female == 1], art[art.female == 0]
    out(f"- Mann-Whitney p: team size {stats.mannwhitneyu(f_.n_authors, m_.n_authors).pvalue:.2g}; "
        f"highest co-author h-index {stats.mannwhitneyu(f_.co_h_max.dropna(), m_.co_h_max.dropna()).pvalue:.2g}.",
        f"- Solo-authored articles: {int((art.n_authors == 1).sum()):,}; female share among them {pct(art[art.n_authors == 1].female):.1f}% "
        f"vs {pct(art[art.n_authors > 1].female):.1f}% for multi-authored.")
    rows = []
    for j, d in art.groupby("journal"):
        rows.append([j, f"{100*(d.n_authors == 1).mean():.1f}", f"{pct(d[d.n_authors == 1].female):.1f}" if (d.n_authors == 1).sum() >= 30 else "-",
                     f"{pct(d[d.n_authors > 1].female):.1f}"])
    out("")
    table(["journal", "% solo-authored", "female % among solo", "female % among multi-authored"], rows)

    # citation model with team controls
    mm = art.dropna(subset=["Citations", "h"]).copy()
    mm["log_cit"] = np.log1p(mm["Citations"])
    mm["log_h"] = np.log1p(mm["h"])
    mm["log_team"] = np.log(mm["n_authors"])
    mm["log_coh"] = np.log1p(mm["co_h_max"].fillna(0))
    rows = []
    for name, f in [("year, journal", "log_cit ~ female + C(year) + C(journal)"),
                    ("+ team size", "log_cit ~ female + C(year) + C(journal) + log_team"),
                    ("+ team size, highest co-author h-index", "log_cit ~ female + C(year) + C(journal) + log_team + log_coh"),
                    ("+ team size, highest co-author h-index, first-author h-index", "log_cit ~ female + C(year) + C(journal) + log_team + log_coh + log_h")]:
        fit = smf.ols(f, data=mm).fit(cov_type="HC1")
        b, se = fit.params["female"], fit.bse["female"]
        rows.append([name, f"{100*(np.exp(b)-1):+.1f}%", f"{100*(np.exp(b-1.96*se)-1):+.1f} to {100*(np.exp(b+1.96*se)-1):+.1f}", f"{fit.pvalues['female']:.2g}"])
    out("Citation models on unique articles (log citations; % difference female vs male first author):", "")
    table(["controls", "% difference", "95% CI", "p"], rows)

    # ---------- 4. citation tails ----------
    out("## 4. Highly cited and uncited articles", "",
        "Citation rank is computed within journal and publication year, on unique articles from 2010-2022 "
        "(later years have had too little time to accumulate citations).", "")
    c = art[(art.year <= 2022) & art["Citations"].notna()].copy()
    c["rank"] = c.groupby(["journal", "year"])["Citations"].rank(pct=True)
    base = pct(c.female)
    rows = []
    for lab, sel in [("all", c), ("top 25%", c[c["rank"] > 0.75]), ("top 10%", c[c["rank"] > 0.90]), ("top 5%", c[c["rank"] > 0.95]),
                     ("top 1%", c[c["rank"] > 0.99]), ("bottom 25%", c[c["rank"] <= 0.25])]:
        lo, hi = wilson(sel.female.sum(), len(sel))
        rows.append([lab, f"{len(sel):,}", f"{pct(sel.female):.1f}", f"{lo:.1f}-{hi:.1f}"])
    table(["group", "articles", "female %", "95% CI"], rows)
    top = c["rank"] > 0.90
    out(f"- Share of articles reaching the top 10%: female {100*top[c.female == 1].mean():.1f}%, male {100*top[c.female == 0].mean():.1f}% "
        f"(chi-square p = {stats.chi2_contingency(pd.crosstab(c.female, top))[1]:.2g}).",
        f"- Uncited articles: female {100*(c[c.female == 1].Citations == 0).mean():.1f}%, male {100*(c[c.female == 0].Citations == 0).mean():.1f}%.",
        f"- Baseline female share in this subset: {base:.1f}%.", "")

    # ---------- 5. trends by journal and country ----------
    out("## 5. Trends 2010-2024 by journal and by country", "")
    d24 = df[df.year <= 2024]
    for by in ["journal", "Country"]:
        rows = []
        for k, d in d24.groupby(by):
            s, p, o, op = trend(d)
            early, late = pct(d[d.year <= 2014].female), pct(d[d.year >= 2020].female)
            rows.append([k, f"{len(d):,}", f"{early:.1f}", f"{late:.1f}", f"{late-early:+.1f}", f"{s:+.2f}", f"{p:.3f}", f"{o:.3f}", f"{op:.2g}"])
        table([by.lower(), "records", "female % 2010-14", "female % 2020-24", "change (pp)", "slope (pp/yr)", "year-level p", "logistic OR/yr", "p"], rows)
    li = smf.logit("female ~ I(year - 2010) * C(journal) + C(Country)", data=d24).fit(disp=0)
    l0 = smf.logit("female ~ I(year - 2010) + C(journal) + C(Country)", data=d24).fit(disp=0)
    lrj = 2 * (li.llf - l0.llf)
    li2 = smf.logit("female ~ I(year - 2010) * C(Country) + C(journal)", data=d24).fit(disp=0)
    lrc = 2 * (li2.llf - l0.llf)
    out(f"- Do trends differ between journals? Likelihood-ratio test of year x journal: p = {stats.chi2.sf(lrj, li.df_model - l0.df_model):.3f}.",
        f"- Do trends differ between countries? Likelihood-ratio test of year x country: p = {stats.chi2.sf(lrc, li2.df_model - l0.df_model):.3f}.", "")

    # ---------- 6. country x journal ----------
    out("## 6. Female share by country and journal (%; cells with fewer than 50 records are blank)", "")
    piv = df.pivot_table(index="Country", columns="journal", values="female", aggfunc=["mean", "count"])
    short = {"Applied Catalysis A: General": "Appl. Catal. A", "Energy Policy": "Energy Policy",
             "International Journal of Greenhouse Gas Control": "IJ GHG Control", "International Journal of Hydrogen Energy": "IJ Hydrogen",
             "Solar Energy": "Solar Energy", "Solar Energy Materials and Solar Cells": "SEMSC"}
    js = list(short)
    table(["country"] + [short[j] for j in js],
          [[cty] + [f"{100*piv['mean'].loc[cty, j]:.1f}" if piv["count"].loc[cty, j] >= 50 else "" for j in js] for cty in piv.index])
    l1 = smf.logit("female ~ C(Country) * C(journal)", data=df).fit(disp=0)
    l2 = smf.logit("female ~ C(Country) + C(journal)", data=df).fit(disp=0)
    out(f"- Country x journal interaction (likelihood-ratio test): p = {stats.chi2.sf(2*(l1.llf-l2.llf), l1.df_model-l2.df_model):.3f}.", "")

    # ---------- 7. multi-country articles ----------
    out("## 7. Articles with authors in more than one study country", "")
    nc = df.groupby("Item DOI")["Country"].nunique()
    art["multi"] = art["Item DOI"].map(nc) > 1
    rows = []
    for lab, d in [("one study country", art[~art.multi]), ("two or more study countries", art[art.multi])]:
        lo, hi = wilson(d.female.sum(), len(d))
        rows.append([lab, f"{len(d):,}", f"{pct(d.female):.1f}", f"{lo:.1f}-{hi:.1f}", f"{d.n_authors.mean():.1f}", f"{d.Citations.mean():.1f}", f"{d.Citations.median():.0f}"])
    table(["articles", "n", "female %", "95% CI", "mean authors", "mean citations", "median citations"], rows)
    out(f"- Chi-square p for female share: {stats.chi2_contingency(pd.crosstab(art.multi, art.female))[1]:.2g}.", "")

    # ---------- 8. keywords ----------
    out("## 8. Author keywords with the highest and lowest female first-author share", "",
        "Unique articles; keywords lower-cased; only keywords used in at least 40 articles. "
        "p compares the keyword's share with all other articles (chi-square), without correction for multiple testing.", "")
    kw = art[["Item DOI", "female", "Keywords"]].dropna(subset=["Keywords"]).copy()
    kw["k"] = kw["Keywords"].str.lower().str.split(";")
    kw = kw.explode("k")
    kw["k"] = kw["k"].str.strip()
    kw = kw[kw.k.str.len() > 1].drop_duplicates(["Item DOI", "k"])
    g = kw.groupby("k")["female"].agg(["sum", "count"])
    g = g[g["count"] >= 40]
    g["pct"] = 100 * g["sum"] / g["count"]
    tot_f, tot_n = art.female.sum(), len(art)
    g["p"] = [stats.chi2_contingency([[r["sum"], r["count"] - r["sum"]], [tot_f - r["sum"], tot_n - r["count"] - (tot_f - r["sum"])]])[1] for _, r in g.iterrows()]
    out(f"{len(g)} keywords qualify. Baseline female share: {pct(art.female):.1f}%.", "")
    for title, sel in [("Highest", g.sort_values("pct", ascending=False).head(12)), ("Lowest", g.sort_values("pct").head(12))]:
        out(f"**{title} female share**", "")
        table(["keyword", "articles", "female %", "95% CI", "p"],
              [[k, int(r["count"]), f"{r['pct']:.1f}", "%.1f-%.1f" % wilson(r["sum"], r["count"]), f"{r['p']:.2g}"] for k, r in sel.iterrows()])
    out(f"- Keywords significantly different from baseline at p < 0.05: {int((g.p < 0.05).sum())} of {len(g)} "
        f"(about {0.05*len(g):.0f} expected by chance).", "")

    os.makedirs("results", exist_ok=True)
    with open(os.path.join("results", "extra_analysis.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
